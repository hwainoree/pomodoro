import {chromium} from '/opt/data/tools/pomodoro-qa/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const url=process.env.POMODORO_URL || 'http://pomodoro.hn.yaaha.net';
const out='/opt/data/apps/hwainoree/pomodoro/qa';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const results=[];const errors=[];
try {
 const context=await browser.newContext({viewport:{width:1280,height:900}});
 const page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 const response=await page.goto(url,{waitUntil:'networkidle'});
 assert.equal(response.status(),200);
 assert.equal(await page.locator('#timer').innerText(),'25:00');results.push('initial focus timer');
 await page.locator('#start-pause').click();await page.waitForTimeout(1300);
 assert.notEqual(await page.locator('#timer').innerText(),'25:00');
 await page.locator('#start-pause').click();const paused=await page.locator('#timer').innerText();
 await page.waitForTimeout(1100);assert.equal(await page.locator('#timer').innerText(),paused);results.push('start/pause real clock');
 await page.reload({waitUntil:'networkidle'});assert.equal(await page.locator('#timer').innerText(),paused);results.push('reload persistence');
 await page.locator('#reset').click();assert.equal(await page.locator('#timer').innerText(),'25:00');
 await page.locator('#mode-short').click();assert.equal(await page.locator('#timer').innerText(),'05:00');results.push('reset and mode selection');
 await page.locator('#duration-focus').fill('0');await page.locator('#save-durations').click();
 assert.match(await page.locator('#settings-message').innerText(),/1.*180/);
 await page.locator('#duration-focus').fill('1');await page.locator('#save-durations').click();
 await page.locator('#mode-focus').click();assert.equal(await page.locator('#timer').innerText(),'01:00');results.push('duration validation and custom lengths');
 await page.evaluate(()=>document.activeElement.blur());
 await page.keyboard.press('Space');assert.equal(await page.locator('#status').innerText(),'Running');
 await page.keyboard.press('Space');await page.keyboard.press('r');assert.equal(await page.locator('#timer').innerText(),'01:00');results.push('keyboard controls');
 await page.evaluate(()=>{
  const saved=JSON.parse(localStorage.getItem('pomodoro.timer.v1'));
  saved.running=true;saved.deadline=Date.now()-1000;saved.mode='focus';saved.completedFocus=3;
  localStorage.setItem('pomodoro.timer.v1',JSON.stringify(saved));
 });
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('#mode-long').getAttribute('aria-pressed'),'true');
 assert.equal(await page.locator('#session-count').innerText(),'4 sessions');
 await page.reload({waitUntil:'networkidle'});assert.equal(await page.locator('#session-count').innerText(),'4 sessions');results.push('overdue fourth session becomes stopped long break exactly once');
 await page.locator('#sound-test').click();await page.waitForTimeout(100);results.push('sound preview handler (audibility not assessed)');
 await page.evaluate(()=>localStorage.clear());await page.reload({waitUntil:'networkidle'});
 await page.screenshot({path:out+'/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile overflow');
 await page.screenshot({path:out+'/mobile.png',fullPage:true});results.push('mobile layout without horizontal overflow');
 assert.deepEqual(errors,[]);results.push('no browser JavaScript or CSP errors');
 await writeFile(out+'/browser-results.json',JSON.stringify({url,passed:results,errors},null,2));
 console.log(JSON.stringify({url,passed:results,errors},null,2));
} finally {await browser.close();}
